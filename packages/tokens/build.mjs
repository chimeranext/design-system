// Style Dictionary build for @chimeranext/tokens.
// Seeded from startups-android-appstore/packages/tokens (config.json css+dart),
// extended with a themed CSS format (dark :root + .light), a Tailwind preset,
// a JS token export (consumed by Storybook Foundations stories), and a Dart class.
//
// Custom formats read the raw token tree (dictionary.tokens) so semantic HSL
// triplets ("257 38% 5%") and the gradient string pass through untouched — no
// color transforms are applied.
import StyleDictionary from "style-dictionary";

const BANNER = "AUTO-GENERATED by @chimeranext/tokens — do not edit. Run: npm run build";
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const strip = (obj) => Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, v.value]));

// --- CSS: dark :root (default) + .light overrides ---------------------------
StyleDictionary.registerFormat({
  name: "css/chimera-themed",
  format: ({ dictionary }) => {
    const t = dictionary.tokens;
    const v = (name, val) => `  --${name}: ${val};`;
    const root = [];
    for (const [k, node] of Object.entries(t.brand)) root.push(v(`brand-${k}`, node.value));
    root.push(v("gradient-brand", t.gradient.brand.value));
    for (const [k, node] of Object.entries(t.font)) root.push(v(`font-${k}`, node.value));
    for (const [k, node] of Object.entries(t.radius)) root.push(v(`radius-${k}`, node.value));
    for (const [k, node] of Object.entries(t.semantic.dark)) root.push(v(k, node.value));
    for (const [k, node] of Object.entries(t.bento.dark)) root.push(v(`bento-${k}`, node.value));
    const light = [];
    for (const [k, node] of Object.entries(t.semantic.light)) light.push(v(k, node.value));
    for (const [k, node] of Object.entries(t.bento.light)) light.push(v(`bento-${k}`, node.value));
    return `/* ${BANNER} */\n:root {\n${root.join("\n")}\n}\n\n.light {\n${light.join("\n")}\n}\n`;
  },
});

// --- Tailwind v3 preset -----------------------------------------------------
StyleDictionary.registerFormat({
  name: "js/chimera-tailwind-preset",
  format: ({ dictionary }) => {
    const t = dictionary.tokens;
    const brand = strip(t.brand);
    const bento = Object.fromEntries(Object.keys(t.bento.dark).map((k) => [k, `var(--bento-${k})`]));
    const preset = {
      darkMode: ["class"],
      theme: {
        extend: {
          colors: {
            border: "hsl(var(--border))",
            input: "hsl(var(--input))",
            ring: "hsl(var(--ring))",
            background: "hsl(var(--background))",
            foreground: "hsl(var(--foreground))",
            primary: { DEFAULT: "hsl(var(--primary))", foreground: "hsl(var(--primary-foreground))" },
            secondary: { DEFAULT: "hsl(var(--secondary))", foreground: "hsl(var(--secondary-foreground))" },
            muted: { DEFAULT: "hsl(var(--muted))", foreground: "hsl(var(--muted-foreground))" },
            accent: { DEFAULT: "hsl(var(--accent))", foreground: "hsl(var(--accent-foreground))" },
            destructive: { DEFAULT: "hsl(var(--destructive))", foreground: "hsl(var(--destructive-foreground))" },
            success: "hsl(var(--success))",
            warning: "hsl(var(--warning))",
            card: { DEFAULT: "hsl(var(--card))", foreground: "hsl(var(--card-foreground))" },
            brand,
            bento,
          },
          fontFamily: {
            heading: ["var(--font-heading)", "Sora Variable", "Sora", "system-ui", "sans-serif"],
            body: ["var(--font-body)", "Inter Variable", "Inter", "system-ui", "sans-serif"],
            mono: ["var(--font-mono)", "JetBrains Mono Variable", "JetBrains Mono", "ui-monospace", "monospace"],
          },
          borderRadius: { lg: t.radius.lg.value, md: t.radius.md.value, sm: t.radius.sm.value },
          backgroundImage: { "brand-gradient": t.gradient.brand.value },
        },
      },
    };
    return `// ${BANNER}\nmodule.exports = ${JSON.stringify(preset, null, 2)};\n`;
  },
});

// --- JS token export (Foundations stories render these real values) ---------
StyleDictionary.registerFormat({
  name: "js/chimera-tokens",
  format: ({ dictionary }) => {
    const t = dictionary.tokens;
    const obj = {
      brand: strip(t.brand),
      gradient: { brand: t.gradient.brand.value },
      font: strip(t.font),
      radius: strip(t.radius),
      semantic: { dark: strip(t.semantic.dark), light: strip(t.semantic.light) },
      bento: { dark: strip(t.bento.dark), light: strip(t.bento.light) },
    };
    return `// ${BANNER}\nexport const tokens = ${JSON.stringify(obj, null, 2)};\nexport default tokens;\n`;
  },
});

// --- Dart: ChimeraTokens (brand + bento Colors, font names, radii) ----------
StyleDictionary.registerFormat({
  name: "dart/chimera-tokens",
  format: ({ dictionary }) => {
    const t = dictionary.tokens;
    const color = (hex) => `Color(0xFF${hex.replace("#", "").toUpperCase()})`;
    const lines = [];
    for (const [k, node] of Object.entries(t.brand)) lines.push(`  static const Color brand${cap(k)} = ${color(node.value)};`);
    lines.push("");
    for (const [k, node] of Object.entries(t.bento.dark)) lines.push(`  static const Color bentoDark${k} = ${color(node.value)};`);
    for (const [k, node] of Object.entries(t.bento.light)) lines.push(`  static const Color bentoLight${k} = ${color(node.value)};`);
    lines.push("");
    for (const [k, node] of Object.entries(t.font)) lines.push(`  static const String font${cap(k)} = '${node.value}';`);
    lines.push("");
    for (const [k, node] of Object.entries(t.radius)) lines.push(`  static const double radius${cap(k)} = ${parseFloat(node.value)};`);
    return `// ${BANNER}\nimport 'dart:ui';\n\n/// Canonical ChimeraNext design tokens — brand palette, bento accents, fonts, radii.\nclass ChimeraTokens {\n  ChimeraTokens._();\n\n${lines.join("\n")}\n}\n`;
  },
});

const sd = new StyleDictionary({
  source: ["tokens.json"],
  // No color transforms: custom formats emit raw values verbatim.
  platforms: {
    css: {
      transforms: ["name/kebab"],
      buildPath: "build/css/",
      files: [{ destination: "variables.css", format: "css/chimera-themed" }],
    },
    tailwind: {
      transforms: ["name/kebab"],
      buildPath: "build/",
      files: [{ destination: "tailwind-preset.js", format: "js/chimera-tailwind-preset" }],
    },
    js: {
      transforms: ["name/kebab"],
      buildPath: "build/",
      files: [{ destination: "tokens.js", format: "js/chimera-tokens" }],
    },
    dart: {
      transforms: ["name/kebab"],
      buildPath: "build/dart/",
      files: [{ destination: "chimera_tokens.dart", format: "dart/chimera-tokens" }],
    },
  },
});

await sd.buildAllPlatforms();
console.log("✓ @chimeranext/tokens built → build/{css/variables.css, tailwind-preset.js, tokens.js, dart/chimera_tokens.dart}");
